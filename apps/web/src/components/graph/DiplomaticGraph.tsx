"use client"

import type { DiplomaticEdge, DiplomaticNode } from "@dipapp/types"
import cytoscape from "cytoscape"
// @ts-expect-error — no types for cytoscape-cose-bilkent
import coseBilkent from "cytoscape-cose-bilkent"
import { forwardRef, useEffect, useImperativeHandle, useMemo, useRef } from "react"
import { useGraphStore } from "@/lib/store/graphStore"

// Register layout once
if (typeof window !== "undefined") {
  cytoscape.use(coseBilkent)
}

// ---------------------------------------------------------------------------
// Visual theme — dark background, degree-sized nodes, glow, affinity colors
// ---------------------------------------------------------------------------

/** Returns a color interpolated by affinity score (0-100):
 *  low → coral, mid → amber, high → cyan */
function affinityColor(score: number): string {
  if (score >= 70) return "#00E5CC"   // teal/cyan — high affinity
  if (score >= 45) return "#FFB300"   // amber    — medium
  return "#FF5252"                    // coral    — low
}

const ORG_COLOR   = "#7B61FF"  // purple for organizations
const EDGE_COLOR: Record<DiplomaticEdge["type"], string> = {
  bilateral_treaty:  "#00E5CC",
  trade_agreement:   "#4CAF50",
  un_vote_alignment: "#64B5F6",
  dispute:           "#FF5252",
}

/**
 * Cytoscape renders labels on a <canvas>, which cannot resolve CSS variables,
 * so the Urbanist family generated by next/font is read from the root element.
 */
function resolveUrbanistFamily(): string {
  if (typeof window === "undefined") return "Urbanist, sans-serif"
  const family = getComputedStyle(document.documentElement)
    .getPropertyValue("--font-urbanist")
    .trim()
  return family ? `${family}, Urbanist, sans-serif` : "Urbanist, sans-serif"
}

export interface DiplomaticGraphHandle {
  fit: () => void
  zoomIn: () => void
  zoomOut: () => void
  focusNode: (nodeId: string) => void
}

interface DiplomaticGraphProps {
  initialNodes?: DiplomaticNode[]
  initialEdges?: DiplomaticEdge[]
}

const DiplomaticGraph = forwardRef<DiplomaticGraphHandle, DiplomaticGraphProps>(
function DiplomaticGraph({
  initialNodes,
  initialEdges,
}, ref) {
  const containerRef = useRef<HTMLDivElement>(null)
  const cyRef = useRef<cytoscape.Core | null>(null)

  const {
    nodes: storeNodes,
    edges: storeEdges,
    filters,
    selectNode,
    setHighlightedPath,
    setNodes,
    setEdges,
    pathRequest,
    clearPath,
  } = useGraphStore()

  // Seed the store from initial (SSR) data on mount
  useEffect(() => {
    if (initialNodes && initialNodes.length > 0) setNodes(initialNodes)
    if (initialEdges && initialEdges.length > 0) setEdges(initialEdges)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  // Memoized so a fallback `[]` doesn't change identity each render and
  // force a full Cytoscape destroy/rebuild.
  const displayNodes = useMemo(
    () => (storeNodes.length > 0 ? storeNodes : (initialNodes ?? [])),
    [storeNodes, initialNodes]
  )
  const displayEdges = useMemo(
    () => (storeEdges.length > 0 ? storeEdges : (initialEdges ?? [])),
    [storeEdges, initialEdges]
  )

  // Apply filters (memoized to avoid rebuilding Cytoscape on every render)
  const filteredNodes = useMemo(
    () =>
      displayNodes.filter((n) => {
        if (filters.regions.length > 0 && !filters.regions.includes(n.region)) return false
        if (n.affinityScore < filters.minAffinityScore) return false
        if (filters.types.length > 0 && !filters.types.includes(n.type)) return false
        return true
      }),
    [displayNodes, filters]
  )
  const filteredEdges = useMemo(() => {
    const filteredNodeIds = new Set(filteredNodes.map((n) => n.id))
    return displayEdges.filter(
      (e) => filteredNodeIds.has(e.source) && filteredNodeIds.has(e.target)
    )
  }, [displayEdges, filteredNodes])

  /**
   * Annotate each edge with rendering metadata:
   *   - `bidirectional`: true when the reverse edge also exists
   *   - `parallelIndex` / `parallelTotal`: position among parallel edges
   *     between the same unordered pair (for curvature spread)
   */
  const annotatedEdges = useMemo(() => {
    // Build a set of directed pairs for bidirectionality check
    const directedPairs = new Set(filteredEdges.map((e) => `${e.source}→${e.target}`))

    // Group edges by unordered pair key to compute parallel offsets
    const groups = new Map<string, DiplomaticEdge[]>()
    filteredEdges.forEach((e) => {
      const key = [e.source, e.target].sort().join("↔")
      if (!groups.has(key)) groups.set(key, [])
      groups.get(key)!.push(e)
    })

    return filteredEdges.map((e) => {
      const key = [e.source, e.target].sort().join("↔")
      const group = groups.get(key)!
      const idx = group.indexOf(e)
      return {
        edge: e,
        bidirectional: directedPairs.has(`${e.target}→${e.source}`),
        parallelIndex: idx,
        parallelTotal: group.length,
      }
    })
  }, [filteredEdges])

  // Build / refresh cytoscape
  useEffect(() => {
    if (!containerRef.current) return

    // Destroy previous instance
    if (cyRef.current) {
      cyRef.current.destroy()
      cyRef.current = null
    }

    const fontFamily = resolveUrbanistFamily()

    // --- Galaxy layout: top-5 anchors + Milky Way spiral for the rest ---
    const W = containerRef.current.offsetWidth  || 1200
    const H = containerRef.current.offsetHeight || 700
    const cx = W / 2
    const cY = H / 2   // "cY" avoids conflict with the Cytoscape `cy` instance below

    // Build degree map
    const degreeMap: Record<string, number> = {}
    annotatedEdges.forEach(({ edge: e }) => {
      degreeMap[e.source] = (degreeMap[e.source] ?? 0) + 1
      degreeMap[e.target] = (degreeMap[e.target] ?? 0) + 1
    })

    // Rank nodes by degree descending
    const sortedByDegree = [...filteredNodes].sort(
      (a, b) => (degreeMap[b.id] ?? 0) - (degreeMap[a.id] ?? 0)
    )
    const rankMap: Record<string, number> = {}
    sortedByDegree.forEach((n, i) => { rankMap[n.id] = i })

    // Top-5 anchor positions from sketch:
    //   1 = center, 2 = top-left, 3 = top-right, 4 = bottom-right, 5 = bottom-left
    const TOP5: Array<{ x: number; y: number }> = [
      { x: cx,              y: cY },              // 1 — center
      { x: cx - W * 0.36,  y: cY - H * 0.32 },  // 2 — top-left
      { x: cx + W * 0.36,  y: cY - H * 0.32 },  // 3 — top-right
      { x: cx + W * 0.36,  y: cY + H * 0.32 },  // 4 — bottom-right
      { x: cx - W * 0.36,  y: cY + H * 0.32 },  // 5 — bottom-left
    ]

    // Fermat (sunflower) spiral for the remaining nodes.
    // Golden angle (≈137.5°) guarantees uniform coverage with no clustering.
    // Radius grows with sqrt(idx) → equal-area packing, like seeds in a sunflower.
    const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5))
    // Scale factor: each step expands by this many model-units per sqrt-unit.
    // Larger → more spread; sized relative to canvas so fit looks good.
    const SPIRAL_SCALE = Math.min(W, H) * 0.065
    // Start the spiral well outside the TOP-5 anchor cloud
    const SPIRAL_OFFSET = Math.min(W, H) * 0.38

    function getGalaxyPos(rank: number): { x: number; y: number } {
      if (rank < 5) return TOP5[rank]
      const idx   = rank - 5
      const angle = idx * GOLDEN_ANGLE
      const r     = SPIRAL_OFFSET + Math.sqrt(idx + 1) * SPIRAL_SCALE
      return {
        x: cx  + r * Math.cos(angle),
        y: cY  + r * Math.sin(angle) * 0.65,  // 0.65 → elliptical to match widescreen
      }
    }

    function getInitialPos(n: DiplomaticNode) {
      return getGalaxyPos(rankMap[n.id] ?? filteredNodes.length)
    }

    const cy = cytoscape({
      container: containerRef.current,
      elements: [
        ...filteredNodes.map((n) => ({
          group: "nodes" as const,
          data: {
            id: n.id,
            label: n.label,
            nodeType: n.type,
            region: n.region,
            affinityScore: n.affinityScore,
            clusterId: n.clusterId,
          },
          position: getInitialPos(n),
        })),
        ...annotatedEdges.map(({ edge: e, bidirectional, parallelIndex, parallelTotal }) => {
          // Spread parallel edges: index 0 → slight left curve, 1 → right, etc.
          // Offset in pixels; centre-pair gets ~0 offset.
          const spread = 40
          const offset = parallelTotal === 1
            ? 0
            : (parallelIndex - (parallelTotal - 1) / 2) * spread

          return {
            group: "edges" as const,
            data: {
              id: `${e.source}-${e.target}-${e.type}`,
              source: e.source,
              target: e.target,
              edgeType: e.type,
              weight: e.weight,
              bidirectional,
              parallelOffset: offset,
              parallelTotal,
            },
          }
        }),
      ],
      style: [
        {
          selector: "node",
          style: {
            "background-color": (ele: cytoscape.NodeSingular) => {
              const t = ele.data("nodeType") as DiplomaticNode["type"]
              if (t === "organization") return ORG_COLOR
              return affinityColor(ele.data("affinityScore") as number ?? 50)
            },
            label: "data(label)",
            "font-size": (ele: cytoscape.NodeSingular) => {
              const deg = ele.degree(false)
              return Math.max(5, Math.min(9, 5 + deg * 0.08))  // 1/5 of original
            },
            "font-family": fontFamily,
            "font-weight": 600,
            color: "#E0F7F4",
            "text-valign": "bottom",
            "text-margin-y": 3,
            "text-outline-color": "#0A1628",
            "text-outline-width": 1,
            width: (ele: cytoscape.NodeSingular) => {
              const deg = ele.degree(false)
              const base = ele.data("nodeType") === "organization" ? 5 : 3
              return Math.max(base, Math.min(12, base + deg * 0.7))  // 1/5 of original
            },
            height: (ele: cytoscape.NodeSingular) => {
              const deg = ele.degree(false)
              const base = ele.data("nodeType") === "organization" ? 5 : 3
              return Math.max(base, Math.min(12, base + deg * 0.7))  // 1/5 of original
            },
            "border-width": 2,
            "border-color": (ele: cytoscape.NodeSingular) => {
              const t = ele.data("nodeType") as DiplomaticNode["type"]
              if (t === "organization") return "#B39DFF"
              return affinityColor(ele.data("affinityScore") as number ?? 50)
            },
            "border-opacity": 0.6,
            "background-opacity": 0.85,
            "shadow-blur": 18,
            "shadow-color": (ele: cytoscape.NodeSingular) => {
              const t = ele.data("nodeType") as DiplomaticNode["type"]
              if (t === "organization") return ORG_COLOR
              return affinityColor(ele.data("affinityScore") as number ?? 50)
            },
            "shadow-opacity": 0.7,
            "shadow-offset-x": 0,
            "shadow-offset-y": 0,
          // eslint-disable-next-line @typescript-eslint/no-explicit-any
          } as any,
        },
        {
          selector: "edge",
          style: {
            "line-color": (ele: cytoscape.EdgeSingular) =>
              EDGE_COLOR[ele.data("edgeType") as DiplomaticEdge["type"]] ?? "#64B5F6",
            "target-arrow-color": (ele: cytoscape.EdgeSingular) =>
              EDGE_COLOR[ele.data("edgeType") as DiplomaticEdge["type"]] ?? "#64B5F6",
            "source-arrow-color": (ele: cytoscape.EdgeSingular) =>
              EDGE_COLOR[ele.data("edgeType") as DiplomaticEdge["type"]] ?? "#64B5F6",
            // Bidirectional edges get arrows on both ends
            "target-arrow-shape": "triangle",
            "source-arrow-shape": (ele: cytoscape.EdgeSingular) =>
              ele.data("bidirectional") ? "triangle" : "none",
            "arrow-scale": 0.7,
            // Use unbundled-bezier so parallel edges don't overlap;
            // parallelOffset drives the control-point distance
            "curve-style": (ele: cytoscape.EdgeSingular) =>
              (ele.data("parallelTotal") as number) > 1 ? "unbundled-bezier" : "bezier",
            "control-point-distances": (ele: cytoscape.EdgeSingular) =>
              [ele.data("parallelOffset") as number],
            "control-point-weights": [0.5],
            width: (ele: cytoscape.EdgeSingular) =>
              Math.max(0.5, (ele.data("weight") as number) * 2),
            opacity: 0.50,
            // Show edge type as a short label on the mid-point
            label: (ele: cytoscape.EdgeSingular) => {
              const t = ele.data("edgeType") as DiplomaticEdge["type"]
              const labels: Record<DiplomaticEdge["type"], string> = {
                bilateral_treaty:  "🤝",
                trade_agreement:   "📦",
                un_vote_alignment: "🗳",
                dispute:           "⚠",
              }
              return labels[t] ?? ""
            },
            "font-size": 9,
            "text-rotation": "autorotate",
            "text-margin-y": -6,
            color: "#FFFFFF",
            "text-opacity": 0.75,
          // eslint-disable-next-line @typescript-eslint/no-explicit-any
          } as any,
        },
        {
          selector: "node.highlighted",
          style: {
            "border-color": "#FFFFFF",
            "border-width": 3,
            "shadow-opacity": 1,
            "shadow-blur": 28,
          },
        },
        {
          selector: "edge.highlighted",
          style: {
            "line-color": "#FFFFFF",
            "target-arrow-color": "#FFFFFF",
            opacity: 0.9,
            width: 3,
          },
        },
        {
          selector: "node:selected",
          style: {
            "border-color": "#FFFFFF",
            "border-width": 3,
            "shadow-blur": 30,
            "shadow-opacity": 1,
          },
        },
      ],
      layout: {
        name: "preset",   // use the positions computed above — no physics pass
        animate: false,
        fit: true,
        padding: 60,
      } as cytoscape.LayoutOptions,
      userZoomingEnabled: true,
      userPanningEnabled: true,
    })

    // Keep node screen sizes constant regardless of zoom level.
    // Cytoscape node width/height are in model units; at zoom z, a model unit
    // = z screen pixels.  Dividing target screen size by z keeps visual size fixed.
    function resizeNodesForZoom() {
      const z = cy.zoom()
      cy.batch(() => {
        cy.nodes().forEach((ele) => {
          const deg = ele.degree(false)
          const isOrg = ele.data("nodeType") === "organization"
          const base = isOrg ? 5 : 3                          // 1/5 of original (24→5, 14→3)
          const screenSz = Math.max(base, Math.min(12, base + deg * 0.7)) // max 12 (was 60)
          const screenFs = Math.max(5, Math.min(9, 5 + deg * 0.08))       // labels: 5-9px
          ele.style({
            width:               screenSz / z,
            height:              screenSz / z,
            "font-size":         screenFs / z,
            "text-outline-width": 2 / z,
          })
        })
      })
    }
    cy.on("zoom", resizeNodesForZoom)
    resizeNodesForZoom() // apply on first render too

    // Tap handler
    cy.on("tap", "node", (evt) => {
      const data = evt.target.data() as {
        id: string
        label: string
        nodeType: DiplomaticNode["type"]
        region: DiplomaticNode["region"]
        affinityScore: number
        clusterId: string
      }
      const node: DiplomaticNode = {
        id: data.id,
        label: data.label,
        type: data.nodeType,
        region: data.region,
        affinityScore: data.affinityScore,
        clusterId: data.clusterId,
      }
      selectNode(node)
    })

    cy.on("tap", (evt) => {
      if (evt.target === cy) {
        selectNode(null)
      }
    })

    cyRef.current = cy

    return () => {
      cy.destroy()
      cyRef.current = null
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [filteredNodes, annotatedEdges])

  /**
   * Highlight the shortest path between two nodes using Dijkstra.
   * Exposed via the ref pattern — parent calls this imperatively.
   */
  const highlightShortestPath = (sourceId: string, targetId: string) => {
    const cy = cyRef.current
    if (!cy) return

    cy.elements().removeClass("highlighted")

    const dijkstra = cy.elements().dijkstra({
      root: cy.getElementById(sourceId),
      weight: (edge) => 1 / ((edge.data("weight") as number) || 0.1),
    })

    const pathTo = dijkstra.pathTo(cy.getElementById(targetId))
    pathTo.addClass("highlighted")
    const pathIds = pathTo.map((el) => el.id())
    setHighlightedPath(pathIds)
  }

  // React to Zustand pathRequest — run Dijkstra when source+target are set
  useEffect(() => {
    if (!pathRequest) return
    highlightShortestPath(pathRequest.source, pathRequest.target)
    clearPath()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [pathRequest])

  useImperativeHandle(ref, () => ({
    fit() { cyRef.current?.fit(undefined, 30) },
    zoomIn() {
      const cy = cyRef.current
      if (!cy) return
      cy.zoom({ level: cy.zoom() * 1.3, renderedPosition: { x: cy.width() / 2, y: cy.height() / 2 } })
    },
    zoomOut() {
      const cy = cyRef.current
      if (!cy) return
      cy.zoom({ level: cy.zoom() / 1.3, renderedPosition: { x: cy.width() / 2, y: cy.height() / 2 } })
    },
    focusNode(nodeId: string) {
      const cy = cyRef.current
      if (!cy) return
      const node = cy.getElementById(nodeId)
      if (!node.length) return
      cy.animate({ center: { eles: node }, zoom: 2.5 }, { duration: 600 })
      node.select()
      // Trigger tap event to open NodeSheet
      const data = node.data() as {
        id: string; label: string; nodeType: DiplomaticNode["type"]
        region: DiplomaticNode["region"]; affinityScore: number; clusterId: string
      }
      selectNode({ id: data.id, label: data.label, type: data.nodeType, region: data.region, affinityScore: data.affinityScore, clusterId: data.clusterId })
    },
  }))

  return (
    <div
      ref={containerRef}
      className="w-full h-full rounded-lg"
      style={{ minHeight: 500, background: "#0A1628" }}
      aria-label="Diplomatic relations graph"
    />
  )
})

DiplomaticGraph.displayName = "DiplomaticGraph"
export default DiplomaticGraph
